/** A pull request's review guide, as T3 Code's Guide tab shows one: numbered stops through the
 * diff, each with what changed, the code that carries it, and what to judge there. */
const guides = new Map();
async function loadGuide(tab, s, write = false) {
  const key = `${tab.key}:${s.url}`;
  const was = guides.get(key);
  guides.set(key, { ...was, loading: true });
  try {
    guides.set(key, { data: await callOn(tab.machine, { cmd: "pr_guide", tab: tab.view.id, pr: s.url, write }) });
  } catch (e) {
    guides.set(key, { ...was, error: String(e).replace(/^gh: /, "") });
  }
  const g = guides.get(key).data;
  clearTimeout(guides.get(key).timer);
  if (g?.run?.state === "running") guides.get(key).timer = setTimeout(() => loadGuide(tab, s), 2500);
  if (tab === active && shownSurface(tab) === s) renderPanel();
}
function writeGuide(tab, s) {
  s.prTab = "guide";
  savePanel(tab);
  loadGuide(tab, s, true);
}

