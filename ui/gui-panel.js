function delimited(text, sep) {
  const rows = [];
  let row = [""];
  let quoted = false;
  for (let i = 0; i < text.length && rows.length < 2000; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') (row[row.length - 1] += '"'), i++;
      else if (c === '"') quoted = false;
      else row[row.length - 1] += c;
    } else if (c === '"') quoted = true;
    else if (c === sep) row.push("");
    else if (c === "\n") {
      rows.push(row);
      row = [""];
    } else if (c !== "\r") row[row.length - 1] += c;
  }
  if (row.length > 1 || row[0]) rows.push(row);
  return `<div class="table-view"><table><thead><tr>${(rows[0] ?? []).map((c) => `<th>${esc(c)}</th>`).join("")}</tr></thead><tbody>${rows.slice(1).map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
}

