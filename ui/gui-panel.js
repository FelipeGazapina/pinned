/** The header's main button, as T3 picks it: Ready for review on a draft, auto-merge while checks
 * are not passing, else Merge by the chosen method. Merging asks again before it runs. */
function prPrimaryAction(d) {
  const state = prState(d);
  if (state === "merged" || state === "closed") return null;
  if (state === "open" && d.mergeable === "CONFLICTING") return { action: "resolve", label: "Resolve conflicts", icon: "wrench" };
  if (state === "draft") return { action: "ready", label: "Ready for review", icon: "git-pull-request" };
  if (d.autoMergeRequest) return { armed: true, label: `Auto-merge (${MERGE_METHODS[(d.autoMergeRequest.mergeMethod ?? "merge").toLowerCase()]?.toLowerCase() ?? "merge"})` };
  const checks = d.statusCheckRollup ?? [];
  const passing = checks.every((c) => checkState(c) === "ok");
  const method = mergeMethod();
  if (!passing) return { action: AUTO[method], label: `Auto-merge (${MERGE_METHODS[method].toLowerCase()})`, confirm: "Confirm auto-merge?", icon: "git-merge" };
  return { action: method, label: MERGE_METHODS[method], confirm: "Confirm merge?", icon: "git-merge" };
}
const prState = (d) => (d.isDraft && (d.state ?? "").toUpperCase() === "OPEN" ? "draft" : (d.state ?? "open").toLowerCase());

let prArmed = null;
function prPrimary(b) {
  const s = shownSurface(active);
  const d = prCache.get(`${active.key}:${s.url}`)?.data;
  const p = d && prPrimaryAction(d);
  if (!p?.action) return;
  if (p.action === "resolve") return askAgent(s, d, "resolve");
  if (p.confirm && prArmed?.button !== p.action) {
    clearTimeout(prArmed?.timer);
    prArmed = { button: p.action, timer: setTimeout(() => ((prArmed = null), renderPanel()), 4000) };
    return renderPanel();
  }
  clearTimeout(prArmed?.timer);
  prArmed = null;
  prAct(s, p.action);
}

