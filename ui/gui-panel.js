    const got = fileLists.get(active?.key);
    const files = (got?.list ?? []).filter((p) => !p.endsWith("/"));
    const scored = [];
    for (const path of files) {
      const name = path.split("/").pop();
      const inName = fuzzyMatch(name, q);
      const inPath = inName ? null : fuzzyMatch(path, q);
      if (q && !inName && !inPath) continue;
      scored.push({ path, name, inName, inPath, score: inName ? (name.toLowerCase().startsWith(q) ? 0 : 1) : 2 });
      if (scored.length > 4000) break;
    }
    scored.sort((a, b) => a.score - b.score || a.path.length - b.path.length);
