/** The new side of each file a diff shows, read when its unchanged lines are opened, by
 * `tab.key`, revision and path. */
const contents = new Map();
const contentKey = (tab, rev, path) => `${tab.key}\n${rev ?? ""}\n${path}`;
async function loadContent(tab, rev, path) {
  const key = contentKey(tab, rev, path);
  if (contents.get(key)?.lines || contents.get(key)?.loading) return contents.get(key);
  contents.set(key, { loading: true });
  const read = (r) => callOn(tab.machine, { cmd: "read_file", tab: tab.view.id, path, root: true, ...(r ? { rev: r } : {}) });
  try {
    // A turn's snapshot can be gone after git gc; the working tree is the next best.
    const file = await read(rev).catch((e) => (rev ? read(null) : Promise.reject(e)));
    contents.set(key, file.text == null ? { error: "This file isn't text." } : { lines: file.text.replace(/\n$/, "").split("\n") });
  } catch (e) {
    contents.set(key, { error: String(e) });
  }
  return contents.get(key);
}

