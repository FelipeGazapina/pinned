function addSurface(tab, surface) {
  const p = panelOf(tab);
  const had = p.surfaces.find((s) => s.id === surface.id);
  if (!had) p.surfaces.push(surface);
  p.active = surface.id;
  p.open = true;
  savePanel(tab);
  renderPanel();
  return had ?? surface;
}

