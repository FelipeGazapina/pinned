  const path = button.closest(".file").dataset.path;
  const id = `${diff.dataset.key}:${path}`;
  const loaded = await loadContent(tab, diff.dataset.rev || null, path);
  if (loaded.error) return flash(`Couldn't open the unchanged lines: ${loaded.error}`);
  const gaps = { ...openGaps.get(id) };
  const i = Number(button.dataset.gap);
  const shown = { top: 0, bottom: 0, ...gaps[i] };
  const how = button.dataset.expand;
