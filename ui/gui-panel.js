/** The branches the Changes scope can compare with: Automatic, then each branch, with a switch to its
 * remote copy where both exist, as T3's base-ref combobox has. */
async function baseMenu(tab) {
  const refs = await callOn(tab.machine, { cmd: "refs", tab: tab.view.id }).catch(() => ({ local: [], remote: [] }));
  const d = diffState(tab);
  const pick = (base) => () => {
    setDiffState(tab, { base });
    renderPanel();
  };
  const names = [...new Set([...refs.local, ...refs.remote.map((r) => r.replace(/^[^/]+\//, ""))])];
  return [
    { group: "Branch", aside: "Remote" },
    { label: "Automatic", radio: true, checked: !d.base, run: pick(null) },
    ...names.map((name) => {
      const local = refs.local.includes(name) ? name : null;
      const remote = refs.remote.find((r) => r.replace(/^[^/]+\//, "") === name) ?? null;
      const chosen = d.base && (d.base === local || d.base === remote) ? d.base : null;
      const value = chosen ?? local ?? remote;
      return {
        label: name,
        radio: true,
        checked: !!chosen,
        run: pick(value),
        toggle: local && remote ? { on: chosen === remote, title: `Use remote version of ${name}`, run: () => pick(chosen === remote ? local : remote)() } : null,
        hint: !local && remote ? "✓" : "",
      };
    }),
  ];
}

