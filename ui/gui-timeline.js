/** 1234 reads 1.2k, as T3 Code's diff counts do. */
function compact(n) {
  for (const [size, unit] of [[1e9, "b"], [1e6, "m"], [1e3, "k"]]) {
    if (n < size) continue;
    const v = n / size;
    return `${v < 10 ? v.toFixed(1).replace(/\.0$/, "") : Math.round(v)}${unit}`;
  }
  return String(n);
}

