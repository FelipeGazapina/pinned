function stripPlan(plan) {
  const lines = plan.trimEnd().split(/\r?\n/);
  const rest = /^\s{0,3}#{1,6}\s+/.test(lines[0] ?? "") ? lines.slice(1) : lines;
  while (rest[0]?.trim() === "") rest.shift();
  if (/^\s{0,3}#{1,6}\s+summary\s*$/i.test(rest[0] ?? "")) {
    rest.shift();
    while (rest[0]?.trim() === "") rest.shift();
  }
  return rest.join("\n");
}
