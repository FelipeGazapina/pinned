/** Enter or blur keeps the trimmed title, Esc keeps the old one; an empty title is refused. */
function editTitle(tab, input) {
  input.focus();
  input.select();
  let done = false;
  const finish = (keep) => {
    if (done) return;
    const title = input.value.trim();
    if (keep && !title) {
      tell("Thread title cannot be empty");
      if (document.activeElement === input) return;
    }
    done = true;
    ui.renaming = null;
    input.onblur = null;
    input.blur();
    if (keep && title && title !== threadTitle(tab)) {
      changeMarks(threadKey(tab), () => {
        if (title === (tab.view.title || firstPrompt(tab))) delete sideMarks.titles[threadKey(tab)];
        else sideMarks.titles[threadKey(tab)] = title;
      });
    }
    renderSidebar();
    if (tab === active) renderThread();
  };
  input.onkeydown = (e) => {
    e.stopPropagation();
    if (e.key === "Enter") {
      e.preventDefault();
      finish(true);
    } else if (e.key === "Escape") {
      e.preventDefault();
      finish(false);
    }
  };
  input.onblur = () => finish(true);
  input.onclick = (e) => e.stopPropagation();
  input.ondblclick = (e) => e.stopPropagation();
}

