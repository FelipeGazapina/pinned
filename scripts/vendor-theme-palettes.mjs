#!/usr/bin/env node
// Writes ui/vendor/theme-palettes.js from T3 Code's packages/shared/src/themePalettes.ts: the
// standard light and dark colors and the built-in palettes, each role as T3 defines it.
//
//   node scripts/vendor-theme-palettes.mjs <t3code checkout>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const t3 = process.argv[2];
if (!t3) throw new Error("usage: vendor-theme-palettes.mjs <t3code checkout>");
const m = await import(path.resolve(t3, "packages/shared/src/themePalettes.ts"));
const data = {
  roles: m.THEME_COLOR_ROLES,
  standard: { light: m.T3_CODE_LIGHT_THEME_COLORS, dark: m.T3_CODE_DARK_THEME_COLORS },
  builtIn: m.BUILT_IN_THEMES.map(({ id, label, appearance, colors, variants }) => ({ id, label, appearance, colors, variants })),
};
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../ui/vendor/theme-palettes.js");
fs.writeFileSync(out, `// Generated by scripts/vendor-theme-palettes.mjs from T3 Code's themePalettes.ts (MIT).\nconst THEME_PALETTES = ${JSON.stringify(data)};\n`);
console.log(`wrote ${out}`);
